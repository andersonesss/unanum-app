def ask_deepseek(system_prompt, user_prompt, temperature=0.85, user_id=None, portrait_hash=None):
    """
    Отправляет запрос к DeepSeek API с кэшированием.
    Если API недоступен - возвращает None.

    Длина ответа ограничивается ТОЛЬКО промптом (SYSTEM_TONE + system_prompt).
    max_tokens в API не передаётся — модель отвечает столько, сколько требует
    контекст промпта.

    portrait_hash — опциональный MD5-хэш портрета. Если передан, _get_cache_key
    не будет делать отдельный SELECT к user_portrait (полезно при параллельных
    вызовах из ThreadPoolExecutor).
    """
    if not DEEPSEEK_API_KEY:
        print("WARN: DEEPSEEK_API_KEY не задан")
        return None

    cache_key = _get_cache_key(system_prompt, user_prompt, user_id, portrait_hash)
    cached = _get_from_cache(cache_key)
    if cached:
        return cached

    headers = {
        "Authorization": f"Bearer {DEEPSEEK_API_KEY}",
        "Content-Type": "application/json"
    }

    messages = [
        {"role": "system", "content": SYSTEM_TONE}
    ]
    
    if system_prompt:
        messages.append({
            "role": "system",
            "content": system_prompt
        })
    
    messages.append({"role": "user", "content": user_prompt})

    data = {
        "model": "deepseek-chat",
        "messages": messages,
        "temperature": temperature
    }

    try:
        response = requests.post(DEEPSEEK_API_URL, json=data, headers=headers, timeout=(30, 120))
        if response.status_code == 200:
            result = response.json()["choices"][0]["message"]["content"]
            _save_to_cache(cache_key, result)
            return result
        else:
            print(f"DeepSeek API error: {response.status_code} - {response.text}")
            return None
    except Exception as e:
        print(f"DeepSeek connection error: {e}")
        return None


def ask_deepseek_stream(system_prompt, user_prompt, temperature=0.85, user_id=None):
    """
    Отправляет запрос к DeepSeek API с stream=True.
    Возвращает генератор чанков текста.
    Не использует кэш.

    Длина ответа ограничивается ТОЛЬКО промптом (SYSTEM_TONE + system_prompt).
    max_tokens в API не передаётся.
    """
    if not DEEPSEEK_API_KEY:
        print("WARN: DEEPSEEK_API_KEY не задан")
        yield None
        return

    headers = {
        "Authorization": f"Bearer {DEEPSEEK_API_KEY}",
        "Content-Type": "application/json"
    }

    messages = [
        {"role": "system", "content": SYSTEM_TONE}
    ]
    
    if system_prompt:
        messages.append({
            "role": "system",
            "content": system_prompt
        })
    
    messages.append({"role": "user", "content": user_prompt})

    data = {
        "model": "deepseek-chat",
        "messages": messages,
        "temperature": temperature,
        "stream": True
    }

    try:
        # timeout=(connect, read):
        #   connect=10 — быстрое обнаружение недоступности DeepSeek (обычно 1-2 сек).
        #   read=60    — запас на паузы между чанками в длинных стримах
        #                (30 сек мало: при генерации длинного текста бывают паузы 20-30+ сек,
        #                 и стрим обрывался с ReadTimeout на середине).
        # Раньше был timeout=30 (одно число — и connect, и read по 30 сек).
        response = requests.post(
            DEEPSEEK_API_URL,
            json=data,
            headers=headers,
            timeout=(10, 60),
            stream=True,
        )
        if response.status_code == 200:
            for line in response.iter_lines():
                if line:
                    line = line.decode('utf-8')
                    if line.startswith('data: '):
                        line = line[6:]
                        if line == '[DONE]':
                            break
                        try:
                            chunk = json.loads(line)
                            delta = chunk['choices'][0].get('delta', {}).get('content', '')
                            if delta:
                                yield delta
                        except json.JSONDecodeError:
                            continue
        else:
            print(f"DeepSeek API stream error: {response.status_code} - {response.text}")
            yield None
    except Exception as e:
        print(f"DeepSeek connection error: {e}")
        yield None


